#!/bin/bash
# Build the Visual Basic compiler of Roslyn (Microsoft.CodeAnalysis.VisualBasic
# + vbc.exe) from the same source tree roslyn.sh built the C# compiler from.
# The VB compiler is written in VB, so this is the one place the seed's
# vbc.exe (Roslyn 3.9, part of the MSYS2 mono 6.12 package, like the seed
# csc) is used: it compiles the VB syntax/error-facts generators and
# Microsoft.CodeAnalysis.VisualBasic.  vbc.exe itself is C#
# (VbcCommandLine.projitems) and is compiled with our csc.  Needed for the one
# VB assembly of the shared framework, Microsoft.VisualBasic.Core.
#
# usage: vbc.sh <roslyn-version> [step...]     steps: gen vb vbc install test
#   (run after roslyn.sh <version>; uses its build tree and its csc.exe)
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
. "$here/../env-m612.sh"
V=${1:?roslyn version}; shift
steps=${*:-gen vb vbc install test}
B=$M612/build/roslyn-$V
OUT=$M612/roslyn-$V
BCSC=$OUT/csc.exe
SEED_VBC=$MONO_LIB/vbc.exe
. "$here/common.sh"
[ -f "$B/obj/Microsoft.CodeAnalysis.dll" ] || die "run roslyn.sh $V first"
REFS=("${NETFX_REFS[@]}" $(pkg_refs))
# sign like roslyn.sh signed Microsoft.CodeAnalysis (older chain builds are unsigned,
# and their InternalsVisibleTo carry no key)
SIGN=(); monodis --assembly "$OUT/Microsoft.CodeAnalysis.dll" | grep -q 'Zero sized public key' || SIGN=(-publicsign -keyfile:"$(keyfile MSShared)")
# eng/targets/Settings.props + the VB SDK's default imports
VBIMPORTS=Microsoft.VisualBasic,System,System.Collections,System.Collections.Generic,System.Diagnostics,System.Linq,System.Threading.Tasks

# vbc_ <log-name> args... : the seed VB compiler via a response file
vbc_() {
  local name=$1; shift
  local rsp="$B/obj/$name.rsp" a rc=0; : > "$rsp"
  for a in "$@"; do
    if [[ $a =~ ^(-[A-Za-z]+):(/.*)$ ]]; then a="${BASH_REMATCH[1]}:$(winpath "${BASH_REMATCH[2]}")"
    elif [[ $a == /* ]]; then a=$(winpath "$a"); fi
    printf '"%s"\n' "$a" >> "$rsp"
  done
  mono "$SEED_VBC" -nologo -noconfig @"$rsp" > "$B/obj/$name.log" 2>&1 || rc=$?
  grep -E 'error BC' "$B/obj/$name.log" | head -40 || true
  echo "vbc $name: rc=$rc, $(grep -c 'error BC' "$B/obj/$name.log" || true) errors"
  return $rc
}

step_gen() {
  cd "$B"; mkdir -p obj/vbgen
  local G=src/Tools/Source/CompilerGeneratorTools/Source
  vbc_ vbgen-syntax -target:exe -out:obj/vbgen/VBSyntaxGenerator.exe -optionstrict:custom -optioninfer+ -vbruntime* \
    -rootnamespace:Microsoft.CodeAnalysis.VisualBasic.Internal.VBSyntaxGenerator \
    -main:Microsoft.CodeAnalysis.VisualBasic.Internal.VBSyntaxGenerator.Program \
    -imports:$VBIMPORTS,System.Collections.ObjectModel,System.Xml.Linq -nostdlib "${TOOLREFS[@]}" \
    -resource:$G/VisualBasicSyntaxGenerator/VBSyntaxModelSchema.xsd,VBSyntaxModelSchema.xsd \
    $(find $G/VisualBasicSyntaxGenerator -name '*.vb') \
    src/Compilers/VisualBasic/Portable/Declarations/DeclarationModifiers.vb src/Compilers/VisualBasic/Portable/Syntax/SyntaxKind.vb
  vbc_ vbgen-errfacts -target:exe -out:obj/vbgen/VBErrorFactsGenerator.exe -optioninfer+ -vbruntime* -imports:$VBIMPORTS \
    -nostdlib "${TOOLREFS[@]}" $(find $G/VisualBasicErrorFactsGenerator -name '*.vb')
  local GD=src/Compilers/VisualBasic/Portable/Generated
  mono obj/vbgen/VBSyntaxGenerator.exe src/Compilers/VisualBasic/Portable/Syntax/Syntax.xml obj/vbgen   # Syntax.xml.{Main,Syntax,Internal}.Generated.vb
  mono obj/gen/BoundTreeGenerator.exe VB src/Compilers/VisualBasic/Portable/BoundTree/BoundNodes.xml obj/vbgen/BoundNodes.xml.Generated.vb
  mono obj/vbgen/VBErrorFactsGenerator.exe src/Compilers/VisualBasic/Portable/Errors/Errors.vb obj/vbgen/ErrorFacts.Generated.vb
  ls obj/vbgen
  log "diff of regenerated vs checked-in generated sources:"
  local f; for f in obj/vbgen/*.vb; do
    [ -f "$GD/$(basename "$f")" ] && { diff -qBw --strip-trailing-cr "$f" "$GD/$(basename "$f")" || true; }
  done
}

step_vb() {
  cd "$B"
  local GD=src/Compilers/VisualBasic/Portable/Generated P=src/Compilers/VisualBasic/Portable
  resgen $P/VBResources.resx obj/Microsoft.CodeAnalysis.VisualBasic.VBResources.resources > /dev/null
  resxgen $P/VBResources.resx obj/VBResources.g.cs Microsoft.CodeAnalysis.VisualBasic.VBResources
  # ResxGen emits C#; the class must live in the VB assembly, so translate it to VB
  python3 -S - obj/VBResources.g.cs obj/VBResources.g.vb <<'EOPY'
import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
out = ['\' <auto-generated> from VBResources.resx </auto-generated>', 'Option Strict On',
       'Namespace Microsoft.CodeAnalysis.VisualBasic', '    Friend NotInheritable Class VBResources',
       '        Private Shared s_resourceManager As Global.System.Resources.ResourceManager',
       '        Friend Shared ReadOnly Property ResourceManager As Global.System.Resources.ResourceManager',
       '            Get', '                If s_resourceManager Is Nothing Then s_resourceManager = New Global.System.Resources.ResourceManager("Microsoft.CodeAnalysis.VisualBasic.VBResources", GetType(VBResources).Assembly)',
       '                Return s_resourceManager', '            End Get', '        End Property',
       '        Friend Shared Property Culture As Global.System.Globalization.CultureInfo']
for m in re.finditer(r'static string @(\w+) => GetResourceString\("((?:[^"\\]|\\.)*)"\);', src):
    out.append('        Friend Shared ReadOnly Property [%s] As String' % m.group(1))
    out.append('            Get')
    out.append('                Return ResourceManager.GetString("%s", Culture)' % m.group(2).replace('\\"', '""').replace('\\\\', '\\'))
    out.append('            End Get')
    out.append('        End Property')
out += ['    End Class', 'End Namespace']
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
EOPY
  printf 'Imports System.Runtime.CompilerServices\n' > obj/vb-attr.vb
  local IVT_PK=; [ ${#SIGN[@]} -gt 0 ] && IVT_PK=", PublicKey=$(tr -d '\n\r' < "$KEYS"/MSShared-*.pubkey.hex)"
  local a; for a in vbc vbi VBCSCompiler Microsoft.CodeAnalysis.VisualBasic.Scripting; do
    echo "<Assembly: InternalsVisibleTo(\"$a$IVT_PK\")>" >> obj/vb-attr.vb; done
  printf '<Assembly: System.Reflection.AssemblyVersion("%s")>\n<Assembly: System.Reflection.AssemblyFileVersion("%s")>\n<Assembly: System.Reflection.AssemblyInformationalVersion("%s (m612 bootstrap)")>\n' \
    "${V%.*}.0.0" "$V.0" "$V" >> obj/vb-attr.vb
  local emb=() f
  for f in Embedded InternalXmlHelper VbCoreSourceText VbMyTemplateText; do
    emb+=(-resource:$P/Symbols/EmbeddedSymbols/$f.vb,$f.vb); done   # RootNamespace is empty
  vbc_ vb -target:library -out:obj/Microsoft.CodeAnalysis.VisualBasic.dll -nostdlib -optimize+ -debug:portable -deterministic \
    -optionstrict+ -optioninfer+ -optionexplicit+ -optioncompare:binary -langversion:latest -removeintchecks+ -vbruntime* -nowarn:40057,42014,42016,41999,42017,42018,42019,42032,42036,42020,42021,42022,42353,42354,42355 \
    -define:TRACE=True "${SIGN[@]}" -imports:$VBIMPORTS,"IdentifierComparison = Microsoft.CodeAnalysis.CaseInsensitiveComparison",Roslyn.Utilities \
    "${REFS[@]}" -r:obj/Microsoft.CodeAnalysis.dll -resource:obj/Microsoft.CodeAnalysis.VisualBasic.VBResources.resources "${emb[@]}" \
    obj/VBResources.g.vb obj/vb-attr.vb obj/vbgen/Syntax.xml.*.Generated.vb obj/vbgen/BoundNodes.xml.Generated.vb obj/vbgen/ErrorFacts.Generated.vb \
    $(find src/Compilers/VisualBasic/BasicAnalyzerDriver -name '*.vb') $(find $P -name '*.vb' ! -path "$GD/*" ! -path "$P/Symbols/EmbeddedSymbols/Embedded.vb" ! -path "$P/Symbols/EmbeddedSymbols/InternalXmlHelper.vb" \
      ! -path "$P/Symbols/EmbeddedSymbols/VbCoreSourceText.vb" ! -path "$P/Symbols/EmbeddedSymbols/VbMyTemplateText.vb") \
    || die "Microsoft.CodeAnalysis.VisualBasic failed (obj/vb.log)"
}

step_vbc() {
  cd "$B"
  printf '[assembly: System.Reflection.AssemblyVersion("%s")]\n[assembly: System.Reflection.AssemblyFileVersion("%s")]\n' "${V%.*}.0.0" "$V.0" > obj/vbc-ver.cs
  csc vbc -nostdlib -optimize+ -debug:portable -deterministic -d:TRACE -nullable:enable -unsafe "${SIGN[@]}" -target:exe -out:obj/vbc.exe \
    -d:NET472 -d:NETFRAMEWORK "${REFS[@]}" -r:obj/Microsoft.CodeAnalysis.dll -r:obj/Microsoft.CodeAnalysis.VisualBasic.dll \
    -main:Microsoft.CodeAnalysis.VisualBasic.CommandLine.Program obj/vbc-ver.cs \
    src/Compilers/VisualBasic/vbc/Program.cs src/Compilers/Shared/RuntimeHostInfo.cs src/Compilers/Shared/NamedPipeUtil.cs \
    src/Compilers/Shared/BuildClient.cs src/Compilers/Shared/BuildServerConnection.cs src/Compilers/Shared/ExitingTraceListener.cs \
    src/Compilers/Shared/Vbc.cs $(find src/Compilers/Core/CommandLine -name '*.cs') || die "vbc failed (obj/vbc.log)"
}

step_install() {
  # vbc was compiled against the current source-built package assemblies.
  # The shared prefix still has Roslyn step 4's seed copies unless refreshed.
  local d
  for d in $(pkg_runtime_files System.Collections.Immutable System.Reflection.Metadata System.Memory \
    System.Buffers System.Runtime.CompilerServices.Unsafe System.Threading.Tasks.Extensions System.Numerics.Vectors); do
    cp "$d" "$OUT/"
  done
  cp "$B"/obj/{Microsoft.CodeAnalysis.VisualBasic.dll,vbc.exe} "$OUT/"
  cp "$B"/obj/Microsoft.CodeAnalysis.VisualBasic.pdb "$B"/obj/vbc.pdb "$OUT/" 2>/dev/null || true
  cp "$B/src/Compilers/VisualBasic/vbc/App.config" "$OUT/vbc.exe.config"
  printf '%s\n' -r:System.dll -r:System.Core.dll -r:System.Xml.dll -r:System.Xml.Linq.dll \
    -imports:Microsoft.VisualBasic,System,System.Collections,System.Collections.Generic,System.Diagnostics,System.Linq > "$OUT/vbc.rsp"
}

step_test() {
  local T=$B/obj/vbtest; mkdir -p "$T"; cd "$T"
  cat > t.vb <<'EOF'
Option Strict On
Module M
    Function Main() As Integer
        Dim xs As List(Of Integer) = {3, 1, 2}.OrderBy(Function(x) x).ToList()
        Console.WriteLine("VB from source: " & String.Join(",", xs.Select(Function(x) x.ToString())) & $" ({xs.Count} items)")
        Return 0
    End Function
End Module
EOF
  mono "$OUT/vbc.exe" -nologo -vbruntime* -out:t.exe t.vb && mono t.exe
}

for s in $steps; do log "vbc $V: $s"; "step_$s"; done
