// ResxGen: generate a strongly typed resource class from a .resx file, in
// the shape produced by Arcade's GenerateResxSource task (which we cannot
// use: it ships as a prebuilt Arcade SDK package).
//
// usage: ResxGen.exe <in.resx> <out.cs> <Namespace.ClassName> [options]
//   --resource-name <name>   manifest resource base name (default: class full name)
//   --public                 public class/members (default internal)
//   --format                 emit FormatXxx(...) helpers for {0}-style strings
//   --no-rm                  do not emit ResourceManager/GetResourceString
//                            (for runtime-style SR classes that provide their own)
//   --sr                     runtime libraries style: emit properties that call
//                            GetResourceString(key) and nothing else
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml;

static class ResxGen
{
    static int Main(string[] args)
    {
        if (args.Length < 3) { Console.Error.WriteLine("usage: ResxGen in.resx out.cs Ns.Class [--public] [--format] [--no-rm] [--sr] [--resource-name n]"); return 2; }
        string inp = args[0], outp = args[1], full = args[2];
        bool pub = false, fmt = false, noRm = false, sr = false; string resName = full;
        for (int i = 3; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--public": pub = true; break;
                case "--format": fmt = true; break;
                case "--no-rm": noRm = true; break;
                case "--sr": sr = true; noRm = true; break;
                case "--resource-name": resName = args[++i]; break;
                default: Console.Error.WriteLine("unknown option " + args[i]); return 2;
            }
        }
        int dot = full.LastIndexOf('.');
        string ns = dot < 0 ? null : full.Substring(0, dot), cls = dot < 0 ? full : full.Substring(dot + 1);
        var doc = new XmlDocument(); doc.Load(inp);
        var entries = new List<KeyValuePair<string, string>>();
        foreach (XmlElement d in doc.SelectNodes("/root/data"))
        {
            if (d.HasAttribute("type") || d.HasAttribute("mimetype")) continue;
            var v = d.SelectSingleNode("value");
            entries.Add(new KeyValuePair<string, string>(d.GetAttribute("name"), v == null ? "" : v.InnerText));
        }
        string acc = pub ? "public" : "internal";
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by bootstrap/m612/tools/ResxGen.cs from " + Path.GetFileName(inp) + " </auto-generated>");
        sb.AppendLine("#nullable disable");
        sb.AppendLine("using System.Reflection;");
        if (ns != null) sb.AppendLine("namespace " + ns + " {");
        sb.AppendLine("    " + acc + " static partial class " + cls + " {");
        if (!noRm)
        {
            sb.AppendLine("        private static global::System.Resources.ResourceManager s_resourceManager;");
            sb.AppendLine("        " + acc + " static global::System.Resources.ResourceManager ResourceManager => s_resourceManager ?? (s_resourceManager = new global::System.Resources.ResourceManager(\"" + resName + "\", typeof(" + cls + ").GetTypeInfo().Assembly));");
            sb.AppendLine("        " + acc + " static global::System.Globalization.CultureInfo Culture { get; set; }");
            sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine("        internal static string GetResourceString(string resourceKey, string defaultValue = null) => ResourceManager.GetString(resourceKey, Culture);");
        }
        var seen = new HashSet<string>();
        foreach (var e in entries)
        {
            string id = Ident(e.Key);
            if (!seen.Add(id)) continue;
            sb.AppendLine("        /// <summary>" + Xml(e.Value) + "</summary>");
            if (sr)
                sb.AppendLine("        internal static string @" + id + " => GetResourceString(\"" + Esc(e.Key) + "\");");
            else
                sb.AppendLine("        " + acc + " static string @" + id + " => GetResourceString(\"" + Esc(e.Key) + "\");");
            if (fmt)
            {
                var ms = Regex.Matches(e.Value, @"\{(\d+)[^}]*\}");
                if (ms.Count > 0)
                {
                    int n = ms.Cast<Match>().Select(m => int.Parse(m.Groups[1].Value)).Max() + 1;
                    var ps = Enumerable.Range(0, n).Select(i => "object p" + i);
                    var ar = Enumerable.Range(0, n).Select(i => "p" + i);
                    sb.AppendLine("        internal static string Format" + id + "(" + string.Join(", ", ps) + ") => string.Format(Culture, GetResourceString(\"" + Esc(e.Key) + "\"), " + string.Join(", ", ar) + ");");
                }
            }
        }
        sb.AppendLine("    }");
        if (ns != null) sb.AppendLine("}");
        File.WriteAllText(outp, sb.ToString());
        return 0;
    }
    static string Ident(string k)
    {
        var sb = new StringBuilder();
        foreach (char c in k) sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }
    static string Esc(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");
    static string Xml(string s)
    {
        s = s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        s = s.Replace("\r", " ").Replace("\n", " ");
        return s.Length > 200 ? s.Substring(0, 200) + "..." : s;
    }
}
