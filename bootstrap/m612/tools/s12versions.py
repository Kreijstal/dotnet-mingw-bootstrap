#!/usr/bin/env python3
"""s12versions.py <feed-dir> [extra.props]: print a PackageVersions.props for the packages in a feed.

This is source-build's version "lifting" (the VMR writes the same file from the packages the
previous repos produced and passes it as DotNetPackageVersionPropsPath; Arcade's DefaultVersions.props
imports it right after the repo's eng/Versions.props).  For every package id I (highest version if
several) it defines  <I-without-dots>PackageVersion  and  <I-without-dots>Version.
"""
import os, re, sys, zipfile

def nuspec_idver(path):
    with zipfile.ZipFile(path) as z:
        n = [x for x in z.namelist() if x.endswith('.nuspec') and '/' not in x][0]
        s = z.read(n).decode('utf-8-sig')
    i = re.search(r'<id>\s*([^<\s]+)\s*</id>', s).group(1)
    v = re.search(r'<version>\s*([^<\s]+)\s*</version>', s).group(1)
    return i, v

def vkey(v):
    core, _, pre = v.partition('-')
    nums = [int(x) for x in re.findall(r'\d+', core)]
    return (nums, pre == '', pre)

feed = sys.argv[1]
best = {}
for f in sorted(os.listdir(feed)):
    if not f.endswith('.nupkg'):
        continue
    i, v = nuspec_idver(os.path.join(feed, f))
    if i not in best or vkey(v) > vkey(best[i]):
        best[i] = v
out = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- m612 S12: generated by s12versions.py from %s -->' % feed.replace('\\', '/'),
       '<Project>', '  <PropertyGroup>']
for i in sorted(best, key=str.lower):
    p = re.sub(r'[^A-Za-z0-9_]', '', i)
    out.append('    <%sPackageVersion>%s</%sPackageVersion>' % (p, best[i], p))
    out.append('    <%sVersion>%s</%sVersion>' % (p, best[i], p))
out += ['  </PropertyGroup>']
if len(sys.argv) > 2:
    out.append('  <Import Project="%s" />' % sys.argv[2])
out.append('</Project>')
print('\n'.join(out))
