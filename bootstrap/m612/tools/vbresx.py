#!/usr/bin/env python3
"""vbresx.py: the VB flavor of Arcade's GenerateResxSource for dotnet/runtime
libraries (OmitGetResourceString; Common/src/System/SR.vb supplies
GetResourceString/Format).

usage: vbresx.py <Strings.resx> <out.vb> <FxResources.Asm.SR>
"""
import sys, xml.etree.ElementTree as ET

resx, out, fx = sys.argv[1:4]
ns, _, cls = fx.rpartition('.')
L = ["' <auto-generated> by bootstrap/m612/tools/vbresx.py from Strings.resx </auto-generated>",
     'Namespace Global.' + ns, '    Friend NotInheritable Class ' + cls, '    End Class', 'End Namespace',
     'Namespace Global.System', '    Partial Friend Class SR',
     '        Private Shared s_resourceManager As Global.System.Resources.ResourceManager',
     '        Friend Shared ReadOnly Property ResourceManager As Global.System.Resources.ResourceManager',
     '            Get',
     '                If s_resourceManager Is Nothing Then s_resourceManager = New Global.System.Resources.ResourceManager(GetType(Global.%s))' % fx,
     '                Return s_resourceManager', '            End Get', '        End Property']
seen = set()
for d in ET.parse(resx).getroot().findall('data'):
    if d.get('type') or d.get('mimetype'): continue
    k = d.get('name')
    ident = ''.join(c if c.isalnum() or c == '_' else '_' for c in k)
    if ident in seen: continue
    seen.add(ident)
    L += ['        Friend Shared ReadOnly Property [%s] As String' % ident, '            Get',
          '                Return GetResourceString("%s")' % k.replace('"', '""'), '            End Get', '        End Property']
L += ['    End Class', 'End Namespace']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
