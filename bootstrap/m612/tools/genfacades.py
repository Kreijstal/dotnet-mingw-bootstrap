#!/usr/bin/env python3
"""genfacades.py: the type forwards of a partial facade (what Arcade's
GenFacades / GenPartialFacadeSource produces for IsPartialFacadeAssembly
projects), without Arcade.

usage: genfacades.py <contract.dll> <partial.dll> <out.cs> [--omit Type]... seed.dll...

For every public top-level type of the contract (the reference assembly)
that the partial implementation (the project compiled once without
forwards) does not define, emit
  [assembly: TypeForwardedTo(typeof(global::Ns.Name<,>))]
if one of the seed assemblies (the project's compile references) defines it.
Types are read with the seed Mono's monodis --typedef.  Exits 1 and lists
the types it could not find.
"""
import re, subprocess, sys

def typedefs(dll):
    out = subprocess.run(['monodis', '--typedef', dll], capture_output=True, text=True).stdout
    r = set()
    for line in out.splitlines():
        m = re.match(r'^\d+: (\S+) \(.*flags=0x([0-9a-f]+)', line)
        if not m or m.group(1) == '(null)': continue
        fl = int(m.group(2), 16)
        if fl & 7 == 1: r.add(m.group(1))       # tdPublic (top level)
    return r

def all_typedefs(dll):   # every top-level type, any visibility
    out = subprocess.run(['monodis', '--typedef', dll], capture_output=True, text=True).stdout
    r = set()
    for line in out.splitlines():
        m = re.match(r'^\d+: (\S+) \(.*flags=0x([0-9a-f]+)', line)
        if m and int(m.group(2), 16) & 6 == 0: r.add(m.group(1))
    return r

def cs_name(t):
    m = re.match(r'^(.*?)`(\d+)$', t)
    if m: return 'global::%s<%s>' % (m.group(1), ',' * (int(m.group(2)) - 1))
    return 'global::' + t

args = sys.argv[1:]
contract, partial, out = args[:3]
omit, seeds, i = set(), [], 3
while i < len(args):
    if args[i] == '--omit': omit.add(args[i + 1]); i += 2
    else: seeds.append(args[i]); i += 1
want = sorted(typedefs(contract) - all_typedefs(partial) - omit)
have = [(s, typedefs(s)) for s in seeds]
lines, missing = [], []
for t in want:
    if any(t in ts for _, ts in have):
        lines.append('[assembly: System.Runtime.CompilerServices.TypeForwardedTo(typeof(%s))]' % cs_name(t))
    else:
        missing.append(t)
open(out, 'w', newline='\n').write('// <auto-generated> by bootstrap/m612/tools/genfacades.py </auto-generated>\n' + '\n'.join(lines) + '\n')
print('genfacades: %d forwards, %d missing' % (len(lines), len(missing)))
for t in missing: print('  missing: ' + t)
sys.exit(1 if missing else 0)
